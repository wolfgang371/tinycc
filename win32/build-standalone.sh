#!/bin/bash
# Build a standalone, single-file tcc.exe (x86_64 Windows) on Linux with mingw-w64.
#
#   win32/build-standalone.sh [output-dir]      (default: build-standalone/ in the source root)
#
# The result carries its headers and runtime (libtcc1.a, *.def) inside the executable and serves them from memory
# (win32/standalone/tcc_embedded.c, libtcc.c built with -DEMBEDDED_RESOURCES): copy the one file anywhere and run
# it - no include/ or lib/ directories next to it. It has the -t symbol tracking like every build of this fork.
#
# Needs: gcc, make, x86_64-w64-mingw32-gcc and -objcopy (Debian/Ubuntu: mingw-w64). Builds out of tree, so the
# source tree is left as it was (an in-tree ./configure build is not touched either).
set -euo pipefail

SRC=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
OUT=$(mkdir -p "${1:-$SRC/build-standalone}" && cd "${1:-$SRC/build-standalone}" && pwd)
WORK=$OUT/work
MINGW=x86_64-w64-mingw32
rm -rf "$WORK"
mkdir -p "$WORK/cross" "$WORK/win" "$WORK/runtime"

# 1. The runtime the embedded tcc.exe links programs against: built by a Linux-hosted cross compiler.
echo "[1/4] runtime (libtcc1.a via the x86_64-win32 cross compiler)"
( cd "$WORK/cross" && "$SRC/configure" >/dev/null && make -s cross-x86_64-win32 >/dev/null )
cp "$WORK/cross/x86_64-win32-libtcc1.a" "$WORK/runtime/libtcc1.a"
cp "$SRC"/win32/lib/*.def "$WORK/runtime/"

# 2. Headers as C strings, keyed by the install layout of a Windows tcc: include/<rel>, where win32/include
#    overrides include/ (as `make install` copies them). tcc_embedded.c matches requested paths by that suffix.
echo "[2/4] headers"
H=$WORK/embedded_headers.h
{
  echo "/* generated by win32/build-standalone.sh - do not edit */"
  echo "typedef struct { const char *path; const char *content; } EmbeddedHeader;"
} > "$H"
declare -A SEEN=()
KEYS=()
for root in "$SRC/win32/include" "$SRC/include"; do     # win32 first: it wins on a name both have
  while IFS= read -r rel; do
    key="include/$rel"
    [ -n "${SEEN[$key]:-}" ] && continue
    SEEN[$key]=1
    KEYS+=("$key")
    var="h_$(printf '%s' "$key" | tr -c 'A-Za-z0-9' '_')"
    {
      echo "static const char ${var}[] ="
      sed 's/\\/\\\\/g; s/"/\\"/g; s/^/    "/; s/$/\\n"/' "$root/$rel"
      echo ";"
    } >> "$H"
  done < <(cd "$root" && find . -name '*.h' | sed 's|^\./||' | LC_ALL=C sort)
done
{
  echo "static const EmbeddedHeader embedded_headers[] = {"
  for key in "${KEYS[@]}"; do
    echo "    {\"$key\", h_$(printf '%s' "$key" | tr -c 'A-Za-z0-9' '_')},"
  done
  echo "    {NULL, NULL}"
  echo "};"
} >> "$H"

# 3. Runtime files as PE objects (objcopy -I binary) plus the table tcc_embedded.c looks them up in (by basename).
echo "[3/4] runtime files"
R=$WORK/embedded_runtime_files.c
NAMES=()
( cd "$WORK/runtime" && for f in *; do
    "$MINGW-objcopy" -I binary -O pe-x86-64 -B i386:x86-64 \
      --rename-section .data=.rodata,alloc,load,readonly,data,contents "$f" "$f.obj"
  done )
for f in "$WORK"/runtime/*; do
  case "$f" in *.obj) continue ;; esac
  NAMES+=("$(basename "$f")")
done
{
  echo "/* generated by win32/build-standalone.sh - do not edit */"
  echo "#include <stddef.h>"
  echo "typedef struct { const char *filename; const unsigned char *data; size_t size; } EmbeddedFile;"
  for n in "${NAMES[@]}"; do
    v=$(printf '%s' "$n" | tr -c 'A-Za-z0-9' '_')
    echo "extern const unsigned char _binary_${v}_start[], _binary_${v}_end[];"
  done
  echo "const int embedded_runtime_count = ${#NAMES[@]};"
  echo "static EmbeddedFile runtime_files[${#NAMES[@]}];"
  echo "const EmbeddedFile* get_embedded_runtime_files(void) {"
  echo "    if (!runtime_files[0].filename) {"
  i=0
  for n in "${NAMES[@]}"; do
    v=$(printf '%s' "$n" | tr -c 'A-Za-z0-9' '_')
    echo "        runtime_files[$i].filename = \"$n\";"
    echo "        runtime_files[$i].data = _binary_${v}_start;"
    echo "        runtime_files[$i].size = (size_t)(_binary_${v}_end - _binary_${v}_start);"
    i=$((i + 1))
  done
  echo "    }"
  echo "    return runtime_files;"
  echo "}"
} > "$R"

# 4. tcc.exe: tcc.c is one translation unit (ONE_SOURCE, the default), so -DEMBEDDED_RESOURCES and libtcc.c's
#    read/lseek/close redirects reach every file that reads through a descriptor (tccpp, tccelf, tccpe, ...).
#    The Windows config.h comes from a Windows-configured build directory; tccdefs_.h from a native c2str.
echo "[4/4] tcc.exe"
#    tcc.h includes "config.h" with quotes, which finds a config.h next to tcc.h before any -I: an in-tree build's
#    (Linux) config.h would win. So tcc.exe is compiled from a copy of the sources without one.
( cd "$WORK/win" && "$SRC/configure" --cpu=x86_64 --targetos=WIN32 --cross-prefix="$MINGW-" >/dev/null )
mkdir -p "$WORK/src"
cp "$SRC"/*.c "$SRC"/*.h "$SRC"/*.def "$WORK/src/"
rm -f "$WORK/src/config.h" "$WORK/src/tccdefs_.h"
gcc -DC2STR "$SRC/conftest.c" -o "$WORK/win/c2str"
"$WORK/win/c2str" "$SRC/include/tccdefs.h" "$WORK/win/tccdefs_.h"
CFLAGS="-O2 -Wall -Wno-unused-result -Wno-unused-function -Wno-stringop-truncation"
"$MINGW-gcc" $CFLAGS -c "$SRC/win32/standalone/tcc_embedded.c" -I"$WORK" -o "$WORK/tcc_embedded.o"
"$MINGW-gcc" $CFLAGS -c "$R" -o "$WORK/embedded_runtime_files.o"
"$MINGW-gcc" $CFLAGS -DEMBEDDED_RESOURCES -I"$WORK/win" -c "$WORK/src/tcc.c" -o "$WORK/tcc.o"
DEFS=$("$MINGW-gcc" -DEMBEDDED_RESOURCES -I"$WORK/win" -E -dM "$WORK/src/tcc.c")
case "$DEFS" in *"define TCC_TARGET_PE 1"*) ;; *) echo "tcc.exe was not configured for the PE target (wrong config.h?)"; exit 1 ;; esac
"$MINGW-gcc" -o "$OUT/tcc.exe" "$WORK/tcc.o" "$WORK/tcc_embedded.o" "$WORK/embedded_runtime_files.o" \
  "$WORK"/runtime/*.obj -static -s

echo "built $OUT/tcc.exe ($(du -h "$OUT/tcc.exe" | cut -f1); ${#KEYS[@]} headers, ${#NAMES[@]} runtime files)"
